def survival_p_interpretation(p_value):

    if p_value < 0.001:
        return "The result is highly statistically significant (p < 0.001)."

    elif p_value < 0.05:
        return f"The result is statistically significant (p = {p_value:.4f})."

    else:
        return f"The result is not statistically significant (p = {p_value:.4f})."


def interpret_hazard_ratio(hr):

    if hr > 1:
        return f"The predictor is associated with a {((hr - 1) * 100):.2f}% increase in hazard."

    elif hr < 1:
        return f"The predictor is associated with a {((1 - hr) * 100):.2f}% decrease in hazard."

    else:
        return "The predictor shows no estimated change in hazard."


