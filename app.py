def create_word_report(data, analysis_results=None):
    report = Document()

    heading = report.add_heading(
        "StatFlow AI - Statistical Analysis Report", 0
    )
    heading.alignment = WD_ALIGN_PARAGRAPH.CENTER

    report.add_heading("1. Dataset Overview", level=1)
    report.add_paragraph(f"Observations: {data.shape[0]}")
    report.add_paragraph(f"Variables: {data.shape[1]}")
    report.add_paragraph(
        f"Total missing values: {int(data.isna().sum().sum())}"
    )

    report.add_heading("2. Variable Information", level=1)

    table = report.add_table(rows=1, cols=4)
    table.style = "Table Grid"

    headers = ["Variable", "Data Type", "Missing Values", "Unique Values"]

    for i, header in enumerate(headers):
        table.rows[0].cells[i].text = header

    for column in data.columns:
        cells = table.add_row().cells
        cells[0].text = str(column)
        cells[1].text = str(data[column].dtype)
        cells[2].text = str(data[column].isna().sum())
        cells[3].text = str(data[column].nunique())

    numeric_data = data.select_dtypes(include=np.number)

    if not numeric_data.empty:
        report.add_heading("3. Descriptive Statistics", level=1)

        summary = numeric_data.describe().T

        summary_table = report.add_table(rows=1, cols=7)
        summary_table.style = "Table Grid"

        headers = [
            "Variable", "Count", "Mean", "Std",
            "Minimum", "Median", "Maximum"
        ]

        for i, header in enumerate(headers):
            summary_table.rows[0].cells[i].text = header

        for variable, row in summary.iterrows():
            cells = summary_table.add_row().cells

            values = [
                variable,
                row["count"],
                row["mean"],
                row["std"],
                row["min"],
                row["50%"],
                row["max"]
            ]

            for i, value in enumerate(values):
                cells[i].text = str(round(value, 3)) if i > 0 else str(value)
    if analysis_results:
        report.add_heading("4. Inferential Statistical Results", level=1)

        for result_item in analysis_results:
            report.add_heading(
                result_item["analysis"], level=2
            )

            report.add_paragraph(
                f"Outcome variable: {result_item['outcome']}"
            )
            report.add_paragraph(
                f"Grouping variable: {result_item['group']}"
            )
            report.add_paragraph(
                f"Group 1 ({result_item['group_1']}): "
                f"N = {result_item['n1']}, "
                f"Mean = {result_item['mean1']:.3f}"
            )
            report.add_paragraph(
                f"Group 2 ({result_item['group_2']}): "
                f"N = {result_item['n2']}, "
                f"Mean = {result_item['mean2']:.3f}"
            )
            report.add_paragraph(
                f"Test statistic: t({result_item['df']:.2f}) "
                f"= {result_item['t']:.4f}"
            )
            report.add_paragraph(
                f"P-value: {result_item['p']:.6f}"
            )
            report.add_paragraph(
                f"Mean difference: "
                f"{result_item['mean_difference']:.4f}"
            )
            report.add_paragraph(
                f"95% Confidence Interval: "
                f"[{result_item['ci_lower']:.4f}, "
                f"{result_item['ci_upper']:.4f}]"
            )
            report.add_paragraph(
                f"Interpretation: {result_item['conclusion']}"
            )
    report.add_paragraph("Generated by StatFlow AI")

    buffer = io.BytesIO()
    report.save(buffer)
    buffer.seek(0)

    return buffer


