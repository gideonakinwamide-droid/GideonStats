def shapiro_result(values):
    values = pd.Series(values).dropna()

    if 3 <= len(values) <= 5000 and values.nunique() > 1:
        result = stats.shapiro(values)
        return f"W = {result.statistic:.4f}, p = {result.pvalue:.4f}"

    return "Not evaluated (requires 3–5000 observations with variation)."

def welch_df(x, y):
    vx = np.var(x, ddof=1)
    vy = np.var(y, ddof=1)
    nx, ny = len(x), len(y)

    numerator = (vx/nx + vy/ny)**2
    denominator = (
        (vx/nx)**2/(nx-1) +
        (vy/ny)**2/(ny-1)
    )

    return numerator / denominator

